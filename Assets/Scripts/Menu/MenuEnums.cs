/// <summary>
/// 設定/メニュー画面のサブ画面の種類。
/// MenuPanel がこの値を見てどのサブ画面を表示するか切り替える。
/// </summary>
public enum MenuScreen {
    Main,          // メニュートップ(環境設定/アイテム一覧/ヘルプの入口)
    Environment,   // 環境設定
    ItemList,      // アイテム一覧
    Help,          // ヘルプ
}

/// <summary>
/// アイテム一覧画面のタブの種類。
/// </summary>
public enum ItemListTab {
    Fashion,     // ファッション(既存の DressUpItem / ItemDatabase を表示)
    Accessory,   // 装飾(未実装。専用データソース追加待ち)
    Other,       // その他・時短アイテム(未実装。専用データソース追加待ち)
}
