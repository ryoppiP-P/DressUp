//  Date   : 2026/9/12
//------------------------------------------------------------------------------
//  段階が進むたびに TutorialManager.AdvanceTo() で即セーブする(=チェックポイント)。
//  強制終了して再起動しても、各シーンの Hook がこの値を見て途中から再開する。
//
//  今回のスコープ: 街(導入)→畑(種植え/加速アイテム/誕生)→着せ替え→街づくりまで。
//==============================================================================

public enum TutorialStage {
    None = 0,           // 未開始
    TownIntroShown,     // 街の導入3行を見せ終わった(畑ボタンをハイライト待ち)
    FarmIntroShown,     // 畑の導入を見せ終わった(鉢をハイライト待ち。種はここで付与)
    SeedPlanted,        // 種を植え終わった(加速アイテムの説明→付与→ハイライト待ち)
    TimeReduceUsed,      // 加速アイテムを使った(誕生待ち)
    FairyBorn,          // 誕生を見せ終わった(着せ替え・命名を経て街に戻るのを待つ)
    TownCreateIntroShown, // 街づくり導入3行を見せ終わった(街クリボタンをハイライト待ち)
    TownCreateEntered,    // 配置モードに入った(装飾を1つ置くのを待つ)
    TownCreateDecorated,  // 装飾を1つ置いた(編集画面を出るのを待って、締めの3行→完了)
    Completed,          // チュートリアル終了
}
